"""Builds dist/tokplan.py: the whole package in one file that runs as a script or imports as a module.

The modules are concatenated in dependency order with their relative imports removed; the UI
assets are embedded so `python tokplan.py ui` works from the single file too.
"""
import base64
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PKG = os.path.join(ROOT, "tokplan")
ORDER = ["hw.py", "models.py", "physics.py", "ui.py", "__init__.py", "cli.py"]


def strip_relative_imports(src: str) -> str:
    """Drops the package's relative imports; an `x as y` alias becomes `y = x` so the name still exists."""
    out = []
    for line in src.splitlines():
        m = re.match(r"^\s*from \.\w* import (.*)$", line)
        if m:
            for item in m.group(1).split(","):
                item = item.strip()
                if " as " in item:
                    a, b = [x.strip() for x in item.split(" as ")]
                    if b != "_plan":
                        out.append("%s = %s" % (b, a))
            continue
        out.append(line)
    return "\n".join(out)


def main() -> None:
    parts = ['"""tokplan, single-file build. See https://github.com/vitalops/tokplan\n\nThis file is generated by tools/onefile.py; edit the package instead."""',
             "from __future__ import annotations", "import base64, os, sys as _sys", '__version__ = "%s"' % version()]
    for name in ORDER:
        with open(os.path.join(PKG, name)) as f:
            src = f.read()
        src = re.sub(r'^"""[\s\S]*?"""\n', "", src, count=1)        # module docstring
        src = src.replace("from __future__ import annotations\n", "")
        src = strip_relative_imports(src)
        if name == "physics.py":
            src = re.sub(r"^def plan\(", "def plan_scenario(", src, flags=re.M)
        if name == "cli.py":
            src = src.replace("plan(Scenario(", "plan_scenario(Scenario(")
            src = re.sub(r'\nif __name__ == "__main__":\n    sys\.exit\(main\(\)\)\n', "\n", src)
        if name == "__init__.py":
            src = re.sub(r'^__version__ = .*$', "", src, flags=re.M)
            src = "_plan = plan_scenario\n" + src
        parts.append("# ─── %s ───" % name)
        parts.append(src)
    # the UI assets, embedded
    ui_dir = os.path.join(PKG, "ui")
    assets = {}
    for fn in sorted(os.listdir(ui_dir)):
        with open(os.path.join(ui_dir, fn), "rb") as f:
            assets[fn] = base64.b64encode(f.read()).decode("ascii")
    parts.append("_UI_ASSETS = " + repr(assets))
    parts.append('''
def _ui_dir():
    import tempfile
    d = os.path.join(tempfile.gettempdir(), "tokplan-ui")
    os.makedirs(d, exist_ok=True)
    for fn, b64 in _UI_ASSETS.items():
        with open(os.path.join(d, fn), "wb") as f:
            f.write(base64.b64decode(b64))
    return d
HERE = _ui_dir()
if __name__ == "__main__":
    _sys.exit(main())
''')
    os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)
    out = os.path.join(ROOT, "dist", "tokplan.py")
    with open(out, "w") as f:
        f.write("\n".join(parts) + "\n")
    print("wrote", out, os.path.getsize(out) // 1024, "KB")


def version() -> str:
    with open(os.path.join(PKG, "__init__.py")) as f:
        return re.search(r'__version__ = "([^"]+)"', f.read()).group(1)


if __name__ == "__main__":
    main()
